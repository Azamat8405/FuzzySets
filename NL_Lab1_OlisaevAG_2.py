import math

# =========== Задача 2

# A — нечёткое множество(словарь)
def F(A):
    # Проверка корректности
    for x, mu in A.items():
        if not (0 <= mu <= 1):
            raise ValueError(f"mu для '{x}' должно быть в [0, 1]")

    # Ближайшее чёткое множество: округление каждого mu к 0 или 1
    C = {x for x, mu in A.items() if mu >= 0.5}

    # Евклидово расстояние
    d = math.sqrt(sum((mu - (1 if x in C else 0)) ** 2
                      for x, mu in A.items()))

    return C, d


A = {
    "Виктор":   0.95,
    "Виктория": 0.60,
    "Вера":  0.40,
    "Валера":  0.80,
    "Вадим":  0.20,
}

# C — ближайшее чёткое множество (множество элементов с μ >= 0.5)
# d — евклидово расстояние от C до A
C, d = F(A)

print(f"Ближайшее чёткое множество C: {C}")
print(f"Евклидово расстояние d = {d:.4f}")